using RachfordRiceData = std::tuple<
  integer const,                // Number of components
  std::vector< real64 > const,  // composition
  std::vector< real64 > const,  // log of k-values
  bool const,                   // expected success of solve
  real64 const,                 // expected mole fractions of the 2-nd phase
  real64 const                  // expected mole fractions of the 3-rd phase
  >;

class RachfordRice3PhaseFixture : public ::testing::TestWithParam< RachfordRiceData >
{
  static constexpr real64 relTol = 1.0e-5;
  static constexpr real64 absTol = 1.0e-7;
  static constexpr integer MAX_NUM_COMP = 12;

public:
  RachfordRice3PhaseFixture() = default;
  ~RachfordRice3PhaseFixture() = default;

  void testSolve( RachfordRiceData const & data )
  {
    integer const numComps = std::get< 0 >( data );
    stackArray1d< real64, MAX_NUM_COMP > composition( numComps );
    stackArray1d< integer, MAX_NUM_COMP > presentComponents;
    createComposition( numComps, composition.toSlice(), presentComponents, std::get< 1 >( data ));
    stackArray2d< real64, 2*MAX_NUM_COMP > kValues( 2, numComps );
    createKValues( numComps, kValues.toSlice(), std::get< 2 >( data ));
    bool const expectedSuccess = std::get< 3 >( data );
    real64 const expectedV2 = std::get< 4 >( data );
    real64 const expectedV3 = std::get< 5 >( data );

    real64 v2 = -1000.0;
    real64 v3 =  4000.0;
    bool const success = RachfordRice::solve( kValues.toSliceConst(),
                                              composition.toSliceConst(),
                                              presentComponents.toSliceConst(),
                                              v2,
                                              v3 );

    ASSERT_EQ( success, expectedSuccess );

    if( expectedSuccess )
    {
      checkRelativeError( expectedV2, v2, relTol, absTol );
      checkRelativeError( expectedV3, v3, relTol, absTol );

      for( integer ic = 0; ic < numComps; ic++ )
      {
        real64 const k2 = kValues( 0, ic ) - 1.0;
        real64 const k3 = kValues( 1, ic ) - 1.0;
        real64 const w = composition[ic] / (1.0 + v2*k2 + v3*k3);
        real64 const x = kValues( 0, ic ) * w;
        real64 const y = kValues( 1, ic ) * w;
        real64 const z = (1.0 - v2 - v3)*w + v2*x + v3*y;
        checkRelativeError( composition[ic], z, relTol, absTol );
      }
    }
  }

protected:
  template< typename CONTAINER, typename ARRAY >
  static void createComposition( integer const numComps,
                                 arraySlice1d< real64 > const & array,
                                 ARRAY & components,
                                 CONTAINER const & data )
  {
    for( integer ic = 0; ic < numComps; ++ic )
    {
      array[ic] = data[ic];
      if( MultiFluidConstants::minForSpeciesPresence < array[ic] )
      {
        components.emplace_back( ic );
      }
    }
  }

  template< typename CONTAINER >
  static void createKValues( integer const numComps,
                             arraySlice2d< real64 > const & array,
                             CONTAINER const & data )
  {
    for( integer ic = 0; ic < numComps; ++ic )
    {
      array( 0, ic ) = LvArray::math::exp( data[ic] );
      array( 1, ic ) = LvArray::math::exp( data[ic+numComps] );
    }
  }
};

TEST_P( RachfordRice3PhaseFixture, testSolve )
{
  testSolve( GetParam() );
}

